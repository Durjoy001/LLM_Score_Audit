def mark_numeric_suspect(fact: Dict[str, Any], chunk_text: str) -> Dict[str, Any]:
    """
    Run a simple validation on facts that contain numbers:
    - Extract numeric fragments from fact.text.
    - If a number does not appear in the source chunk, mark it as possible numeric hallucination.
    - Add meta.suspect_numeric = True/False.
    """
    text = fact.get("text", "") or ""
    nums = re.findall(r"\d+", text)
    if not nums:
        return fact  # No numbers to check.

    chunk_flat = (chunk_text or "").replace(" ", "")
    suspect = False
    for n in nums:
        if n not in chunk_flat:
            suspect = True
            break

    meta = fact.get("meta", {})
    if not isinstance(meta, dict):
        meta = {}
    meta["suspect_numeric"] = suspect
    fact["meta"] = meta
    return fact

def normalize_fact(
    fact: Dict[str, Any],
    proposal_id: str,
    chunk_index: int,
    start: int,
    end: int,
) -> Dict[str, Any]:
    """
    Add metadata to each fact and clean dimensions/type.
    Also supplement dimension labels from type and text so useful information is not dropped.
    """
    text = fact.get("text", "")
    if not isinstance(text, str):
        text = str(text)
    text = _normalize_fact_text(text)

    # Clean raw dimension labels.
    dims = fact.get("dimensions", [])
    if not isinstance(dims, list):
        dims = []
    dims_clean = [d for d in dims if isinstance(d, str) and d in VALID_DIMENSIONS]

    type_val = fact.get("type", "other")
    if type_val not in VALID_TYPES:
        type_val = "other"

    # ===== Auto-correct market facts before type-to-dimensions mapping =====
    # If the LLM did not label a clearly market/business fact as market, force type="market".
    if type_val not in ["market", "risk", "mitigation"]:
        if _looks_like_market_fact(text):
            type_val = "market"

    # Start with existing dimensions, then supplement from type/text.
    dim_set = set(dims_clean)

    # ===== 1. Type-to-dimensions mapping =====
    if type_val in ["team_member", "org_structure"]:
        # Team members and organization structure clearly belong to team.
        dim_set.add("team")

    elif type_val == "collaboration":
        # Collaboration is both team coordination and strategy.
        dim_set.update(["team", "strategy"])

    elif type_val == "pipeline":
        # A pipeline reflects both objectives and strategy.
        dim_set.update(["objectives", "strategy"])

    elif type_val == "milestone":
        # A milestone reflects staged objectives and execution feasibility.
        dim_set.update(["objectives", "feasibility"])

    elif type_val == "clinical_design":
        # Clinical design reflects objective path, strategy, and feasibility.
        dim_set.update(["objectives", "strategy", "feasibility"])

    elif type_val in ["market", "product"]:
        # Market/product facts usually touch commercial strategy and feasibility.
        dim_set.update(["objectives", "strategy", "feasibility"])

    elif type_val in ["tech_route", "regulatory"]:
        # Technical and regulatory routes are strategy and also affect feasibility.
        dim_set.update(["strategy", "feasibility"])

    elif type_val == "funding_source":
        # Funding source affects strategic planning and feasibility.
        dim_set.update(["strategy", "feasibility"])

    elif type_val == "ip_asset":
        # IP assets reflect innovation and longer-term feasibility.
        dim_set.update(["innovation", "feasibility"])

    elif type_val == "evidence":
        # Evidence supports innovation value and feasibility.
        dim_set.update(["innovation", "feasibility"])

    elif type_val == "ai_model":
        # AI models are innovation signals and often part of strategy.
        dim_set.update(["innovation", "strategy"])

    elif type_val in ["resource", "budget_item", "risk", "mitigation"]:
        # Resources, budget, risks, and mitigations primarily affect feasibility.
        dim_set.add("feasibility")

    # ===== 2. If still unlabeled, infer dimensions from text keywords. =====
    if not dim_set:
        inferred = _infer_dims_from_text(text)
        for d in inferred:
            dim_set.add(d)

    # ===== 3. Final fallback: avoid losing the fact completely. =====
    if not dim_set:
        dim_set.add("feasibility")

    priority = ["team", "objectives", "strategy", "innovation", "feasibility"]
    dims_final = [d for d in priority if d in dim_set]

    meta = fact.get("meta", {})
    if not isinstance(meta, dict):
        meta = {}
    meta.update(
        {
            "proposal_id": proposal_id,
            "chunk_index": chunk_index,
            "char_start": start,
            "char_end": end,
        }
    )

    # ==== Compute primary_dimension ====
    primary_dim = None
    if dims_final:
        # Simple priority rule; tune as needed for the business domain.
        # Pick the highest-priority dimension present in dims_final.
        for d in priority:
            if d in dims_final:
                primary_dim = d
                break
        if primary_dim is None:
            primary_dim = dims_final[0]
    else:
        primary_dim = "feasibility"  # This should not happen because of the fallback above.

    return {
        "text": text,
        "dimensions": dims_final,
        "type": type_val,
        "primary_dimension": primary_dim,
        "meta": meta,
    }

def run_extract(proposal_id: str, max_chars: int = 1800, overlap: int = 400):
    stage_start = time.perf_counter()
    full_text = load_full_text(proposal_id)
    _print_input_diagnostics(proposal_id, full_text, max_chars=max_chars, overlap=overlap)
    chunks = make_chunks(full_text, max_chars=max_chars, overlap=overlap)
    _print_chunk_plan(chunks)

    out_dir = EXTRACTED_DIR / proposal_id
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "raw_facts.jsonl"
    audit_path = out_dir / "stage1_audit.json"

    total_facts = 0
    deduped_exact_facts = 0
    # Track fact counts per dimension for sanity checks.
    dim_counts = {dim: 0 for dim in VALID_DIMENSIONS}
    type_counts = {typ: 0 for typ in VALID_TYPES}
    primary_dim_counts = {dim: 0 for dim in VALID_DIMENSIONS}
    suspect_numeric_count = 0
    chunk_audit = []

    def process_chunk(ch: Dict[str, Any]) -> Dict[str, Any]:
        chunk_start = time.perf_counter()
        idx = ch["index"]
        chunk_len = ch["end"] - ch["start"]
        _log(
            "CHUNK",
            f"start chunk={idx+1}/{len(chunks)} range={ch['start']}:{ch['end']} "
            f"chars={chunk_len}"
        )
        _log("PREVIEW", f"chunk={idx+1} text_preview={_preview_text(ch['text'])}")
        chunk_trace = {
            "chunk_index": idx,
            "chunk_number": idx + 1,
            "char_start": ch["start"],
            "char_end": ch["end"],
            "char_len": chunk_len,
            "preview": _preview_text(ch["text"]),
            "llm_calls": [],
            "dense_retry_triggered": False,
            "dense_retry_used": False,
        }

        # First normal extraction pass.
        data = call_llm_for_chunk(ch["text"], trace=chunk_trace)
        facts = data.get("facts", [])
        if not isinstance(facts, list):
            facts = []
        chunk_trace["raw_fact_count"] = len(facts)

        # If a long chunk produces too few facts, try one dense retry.
        if chunk_len >= 1200 and len(facts) < 5:
            chunk_trace["dense_retry_triggered"] = True
            _log(
                "WARN",
                f"chunk={idx+1} long chunk produced few facts "
                f"(chars={chunk_len}, raw_facts={len(facts)}); trying dense retry"
            )
            dense_data = call_llm_for_chunk(ch["text"], dense=True, trace=chunk_trace)
            dense_facts = dense_data.get("facts", [])
            if isinstance(dense_facts, list) and len(dense_facts) > len(facts):
                _log(
                    "CHUNK",
                    f"chunk={idx+1} dense retry improved facts "
                    f"normal={len(facts)} dense={len(dense_facts)}; using dense result"
                )
                facts = dense_facts
                chunk_trace["dense_retry_used"] = True
            else:
                _log(
                    "CHUNK",
                    f"chunk={idx+1} dense retry did not improve facts "
                    f"normal={len(facts)} dense={len(dense_facts) if isinstance(dense_facts, list) else 'invalid'}; "
                    f"keeping normal result"
                )
            chunk_trace["dense_fact_count"] = len(dense_facts) if isinstance(dense_facts, list) else 0

        normalized_list = []
        skipped_non_dict = 0
        skipped_empty_text = 0
        skipped_duplicate_text = 0
        for fact in facts:
            if not isinstance(fact, dict):
                skipped_non_dict += 1
                continue

            # Mark possible numeric hallucinations using the source chunk.
            fact = mark_numeric_suspect(fact, ch["text"])

            norm = normalize_fact(
                fact,
                proposal_id=proposal_id,
                chunk_index=idx,
                start=ch["start"],
                end=ch["end"],
            )

            # Drop empty fact text.
            fact_text = norm["text"]
            if fact_text:
                normalized_list.append(norm)
            else:
                skipped_empty_text += 1

        dist = _fact_distribution(normalized_list)
        chunk_trace.update(
            {
                "written_fact_count": len(normalized_list),
                "skipped_non_dict": skipped_non_dict,
                "skipped_empty_text": skipped_empty_text,
                "skipped_duplicate_text": skipped_duplicate_text,
                "elapsed_sec": round(time.perf_counter() - chunk_start, 2),
                "distribution": dist,
                "fact_previews": [_preview_text(f.get("text", ""), 220) for f in normalized_list[:5]],
            }
        )
        return {
            "idx": idx,
            "chunk_len": chunk_len,
            "normalized_list": normalized_list,
            "chunk_trace": chunk_trace,
            "dist": dist,
        }

    _write_progress(0, len(chunks), proposal_id)
    chunk_workers = _bounded_worker_count(STAGE1_CHUNK_WORKERS, 1, len(chunks))
    _log("CONCURRENCY", f"stage1_chunks workers={chunk_workers} chunks={len(chunks)}")
    chunk_results: Dict[int, Dict[str, Any]] = {}
    completed_chunks = 0
    if chunk_workers > 1:
        with ThreadPoolExecutor(max_workers=chunk_workers) as pool:
            future_map = {pool.submit(process_chunk, ch): ch["index"] for ch in chunks}
            for future in as_completed(future_map):
                result = future.result()
                chunk_results[result["idx"]] = result
                completed_chunks += 1
                _write_progress(completed_chunks, len(chunks), proposal_id)
                _log(
                    "CHUNK",
                    f"completed chunk={result['idx']+1}/{len(chunks)} "
                    f"completed_chunks={completed_chunks}/{len(chunks)} "
                    f"elapsed_sec={result['chunk_trace']['elapsed_sec']}"
                )
    else:
        for ch in chunks:
            result = process_chunk(ch)
            chunk_results[result["idx"]] = result
            completed_chunks += 1
            _write_progress(completed_chunks, len(chunks), proposal_id)

    written_fact_keys = set()

    with out_path.open("w", encoding="utf-8") as f_out:
        for idx in sorted(chunk_results):
            result = chunk_results[idx]
            normalized_list = result["normalized_list"]
            chunk_trace = result["chunk_trace"]
            chunk_len = result["chunk_len"]
            written_list = []

            for fact in normalized_list:
                if DEDUP_EXACT_FACTS:
                    fact_key = (
                        _normalize_fact_text(fact.get("text", "")).lower(),
                        fact.get("type", "other"),
                        tuple(sorted(fact.get("dimensions", []))),
                    )
                    if fact_key in written_fact_keys:
                        deduped_exact_facts += 1
                        chunk_trace["skipped_duplicate_text"] = chunk_trace.get("skipped_duplicate_text", 0) + 1
                        continue
                    written_fact_keys.add(fact_key)
                written_list.append(fact)

            dist = _fact_distribution(written_list)
            chunk_trace["written_fact_count"] = len(written_list)
            chunk_trace["distribution"] = dist
            chunk_trace["fact_previews"] = [_preview_text(f.get("text", ""), 220) for f in written_list[:5]]

            for fact in written_list:
                f_out.write(json.dumps(fact, ensure_ascii=False) + "\n")
                total_facts += 1
                # Update distribution counters.
                for d in fact.get("dimensions", []):
                    if d in dim_counts:
                        dim_counts[d] += 1
                fact_type = fact.get("type", "other")
                if fact_type in type_counts:
                    type_counts[fact_type] += 1
                primary_dim = fact.get("primary_dimension", "")
                if primary_dim in primary_dim_counts:
                    primary_dim_counts[primary_dim] += 1
                if fact.get("meta", {}).get("suspect_numeric"):
                    suspect_numeric_count += 1

            chunk_audit.append(chunk_trace)
            if len(written_list) < LOW_FACT_WARN_THRESHOLD and chunk_len >= 500:
                _log(
                    "WARN",
                    f"chunk={idx+1} wrote only {len(written_list)} fact(s) from {chunk_len} chars; "
                    f"inspect this chunk in stage1_audit.json"
                )
            _log(
                "CHUNK",
                f"done chunk={idx+1}/{len(chunks)} raw_facts={chunk_trace.get('raw_fact_count', 0)} "
                f"written_facts={len(written_list)} cumulative_facts={total_facts} "
                f"elapsed_sec={chunk_trace['elapsed_sec']}"
            )
            _log("CHUNK", f"chunk={idx+1} dims={json.dumps(dist['dimensions'], ensure_ascii=False)}")
            _log("CHUNK", f"chunk={idx+1} types={json.dumps(dist['types'], ensure_ascii=False)}")
            if dist["suspect_numeric"]["count"]:
                _log("WARN", f"chunk={idx+1} suspect_numeric_facts={dist['suspect_numeric']['count']}")

    elapsed_total = time.perf_counter() - stage_start
    _log("OK", f"raw facts written path={out_path} total_facts={total_facts}")
    if DEDUP_EXACT_FACTS:
        _log("SUMMARY", f"deduped_exact_facts={deduped_exact_facts}")

    # ===== Global dimension distribution check =====
    _log("SUMMARY", "dimension distribution based on raw_facts.jsonl")
    for dim in VALID_DIMENSIONS:
        _log("SUMMARY", f"{dim}={dim_counts[dim]} facts")
    _log("SUMMARY", f"primary_dimension_counts={json.dumps(primary_dim_counts, ensure_ascii=False)}")
    _log("SUMMARY", f"type_counts={json.dumps(type_counts, ensure_ascii=False)}")
    _log("SUMMARY", f"suspect_numeric_facts={suspect_numeric_count}")
    _log("SUMMARY", f"elapsed_sec={elapsed_total:.2f}")

    # Simple sanity check: warn if any dimension is unusually sparse. This does not stop the run.
    if total_facts > 0:
        avg = total_facts / len(VALID_DIMENSIONS)
        for dim in VALID_DIMENSIONS:
            if dim_counts[dim] < max(8, 0.25 * avg):
                _log(
                    "WARN",
                    f"dimension={dim} has only {dim_counts[dim]} facts, below average={avg:.1f}; "
                    f"check raw_facts.jsonl and stage1_audit.json"
                )
    else:
        _log("WARN", "Stage 1 produced zero facts.")

    audit = {
        "proposal_id": proposal_id,
        "model": OPENAI_MODEL,
        "input_path": str((PREPARED_DIR / proposal_id / "full_text.txt").resolve()),
        "output_path": str(out_path.resolve()),
        "max_chars": max_chars,
        "overlap": overlap,
        "chunk_workers": chunk_workers,
        "input_chars": len(full_text),
        "chunk_count": len(chunks),
        "total_facts": total_facts,
        "deduped_exact_facts": deduped_exact_facts,
        "elapsed_sec": round(elapsed_total, 2),
        "dimension_counts": dim_counts,
        "primary_dimension_counts": primary_dim_counts,
        "type_counts": type_counts,
        "suspect_numeric_facts": suspect_numeric_count,
        "chunks": chunk_audit,
    }
    audit_path.write_text(json.dumps(audit, ensure_ascii=False, indent=2), encoding="utf-8")
    _log("OK", f"stage1_audit.json written path={audit_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Stage 1: extract atomic facts by chunk (raw_facts.jsonl)"
    )
    parser.add_argument(
        "--proposal_id",
        required=False,
        help="Proposal ID corresponding to src/data/prepared/<proposal_id>",
    )
    parser.add_argument(
        "--max_chars",
        type=int,
        default=1800,
        help="Maximum characters per chunk (default: 1800)",
    )
    parser.add_argument(
        "--overlap",
        type=int,
        default=400,
        help="Character overlap between chunks (default: 400)",
    )
    args = parser.parse_args()

    if args.proposal_id:
        pid = args.proposal_id
    else:
        pid = find_latest_prepared_proposal()

    run_extract(pid, max_chars=args.max_chars, overlap=args.overlap)


if __name__ == "__main__":
    main()
