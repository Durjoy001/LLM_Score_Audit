def make_chunks(text: str, max_chars: int = 1800, overlap: int = 400) -> List[Dict[str, Any]]:
    """
    Split text into overlapping character-based chunks; this does not split by sentence.
    The default max_chars=1800 and overlap=400 keep chunks dense enough for good coverage.
    Returns a list where each item contains text, start, end, and index.
    """
    chunks = []
    n = len(text)
    if n == 0:
        return chunks

    idx = 0
    chunk_idx = 0
    while idx < n:
        end = min(n, idx + max_chars)
        chunk_text = text[idx:end]
        chunks.append(
            {
                "index": chunk_idx,
                "start": idx,
                "end": end,
                "text": chunk_text,
            }
        )
        chunk_idx += 1
        if end == n:
            break
        idx = max(0, end - overlap)

    _log("INFO", f"created chunks count={len(chunks)} max_chars={max_chars} overlap={overlap}")
    return chunks


def call_llm_for_chunk(
    chunk_text: str,
    attempt: int = 1,
    dense: bool = False,
    trace: Dict[str, Any] | None = None,
) -> Dict[str, Any]:
    """
    Call OpenAI to extract facts from one chunk.
    - attempt > 1: retry after invalid JSON, with stricter JSON instructions.
    - dense = True: second-pass extraction for long chunks that produced too few facts.
    """
    extra_hint_parts = []

    if attempt > 1:
        extra_hint_parts.append(
            "Important: your previous JSON response was too long or invalid and could not be parsed. "
            "This time, limit facts to at most 18 items and ensure the JSON syntax is valid."
        )

    if dense:
        extra_hint_parts.append(
            "Important: this text chunk is information-rich. In this extraction pass, cover all key facts "
            "related to team, objectives, strategy, innovation, and feasibility. Prefer 15-22 facts when "
            "the source supports them, and cover different dimensions and themes instead of one narrow area."
        )

    extra_hint = ""
    if extra_hint_parts:
        extra_hint = "\n\n" + "\n".join(extra_hint_parts)

    messages = [
        {
            "role": "system",
            "content": "You are a rigorous fact extractor. Extract atomic facts only from the given text chunk. Do not invent facts.",
        },
        {
            "role": "user",
            "content": FACT_PROMPT
            + extra_hint
            + "\n\n=== Text chunk starts ===\n"
            + chunk_text.strip(),
        },
    ]

    call_start = time.perf_counter()
    mode = "dense" if dense else "normal"
    _log(
        "LLM",
        f"call_start mode={mode} attempt={attempt} chunk_chars={len(chunk_text)} "
        f"prompt_chars={sum(len(m.get('content', '')) for m in messages if isinstance(m.get('content'), str))}"
    )
    try:
        resp = client.chat.completions.create(
            model=OPENAI_MODEL,
            messages=messages,
            response_format={"type": "json_object"},
            temperature=0.0,
            max_tokens=1800,
        )
    except Exception as e:
        elapsed = time.perf_counter() - call_start
        _log("ERROR", f"LLM call failed mode={mode} attempt={attempt} elapsed_sec={elapsed:.2f}: {e}")
        if trace is not None:
            trace.setdefault("llm_calls", []).append(
                {
                    "mode": mode,
                    "attempt": attempt,
                    "elapsed_sec": round(elapsed, 2),
                    "ok": False,
                    "error": str(e),
                }
            )
        raise

    raw = resp.choices[0].message.content
    elapsed = time.perf_counter() - call_start
    usage = getattr(resp, "usage", None)
    usage_data = None
    if usage is not None:
        usage_data = {
            "prompt_tokens": getattr(usage, "prompt_tokens", None),
            "completion_tokens": getattr(usage, "completion_tokens", None),
            "total_tokens": getattr(usage, "total_tokens", None),
        }
    _log(
        "LLM",
        f"call_done mode={mode} attempt={attempt} elapsed_sec={elapsed:.2f} "
        f"raw_chars={len(raw or '')} usage={json.dumps(usage_data, ensure_ascii=False)}"
    )
    if trace is not None:
        trace.setdefault("llm_calls", []).append(
            {
                "mode": mode,
                "attempt": attempt,
                "elapsed_sec": round(elapsed, 2),
                "ok": True,
                "raw_chars": len(raw or ""),
                "usage": usage_data,
            }
        )
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as e:
        _log("WARN", f"JSON parse failed mode={mode} attempt={attempt}: {e}")
        _log("WARN", f"raw_response_preview={_preview_text(raw or '', 1000)}")
        if trace is not None:
            trace["json_parse_failed"] = True
        if attempt == 1:
            _log("INFO", "retrying chunk with stricter JSON instruction")
            return call_llm_for_chunk(chunk_text, attempt=2, dense=dense, trace=trace)
        # If the second attempt still fails, surface the parsing error.
        raise e

    if not isinstance(data, dict):
        data = {"facts": []}
    if "facts" not in data or not isinstance(data["facts"], list):
        data["facts"] = []

    _log("LLM", f"parsed_facts mode={mode} attempt={attempt} count={len(data['facts'])}")
    return data

