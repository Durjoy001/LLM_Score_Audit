def find_latest_prepared_proposal() -> str:
    if not PREPARED_DIR.exists():
        raise FileNotFoundError(f"Prepared directory not found: {PREPARED_DIR}")

    candidates = []
    for d in PREPARED_DIR.iterdir():
        if d.is_dir():
            candidates.append((d.stat().st_mtime, d.name))

    if not candidates:
        raise FileNotFoundError(f"No proposal subdirectories found under prepared directory: {PREPARED_DIR}")

    proposal_id = max(candidates, key=lambda x: x[0])[1]
    _log("INFO", f"[auto] selected latest prepared proposal_id={proposal_id}")
    return proposal_id


