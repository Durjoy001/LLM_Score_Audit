def _preview_text(text: str, limit: int = PREVIEW_CHARS) -> str:
    text = str(text or "")
    text = text.replace("\uf0b7", "•")
    text = " ".join(text.split())
    if not text:
        return "<empty>"
    if len(text) <= limit:
        return text
    return text[:limit] + " ..."


def _normalize_fact_text(text: str) -> str:
    """
    Normalize fact text for cleanup and duplicate detection.

    The goal is not to rewrite the fact, only to remove layout noise that tends
    to appear in chunked extraction, such as bullets, repeated whitespace, and
    trailing punctuation jitter.
    """
    text = str(text or "").replace("\uf0b7", "•")
    text = " ".join(text.split()).strip()
    text = re.sub(r"^[•\-–—]+\s*", "", text)
    text = re.sub(r"^(?:\[\s*)?(?:fact|point|note)\s*\d*[:\].-]*\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    text = re.sub(r"([,;:!?]){2,}$", r"\1", text)
    return text.strip()


def _count_values(items: List[str]) -> Dict[str, int]:
    counts = {}
    for item in items:
        counts[item] = counts.get(item, 0) + 1
    return counts


def _fact_distribution(facts: List[Dict[str, Any]]) -> Dict[str, Dict[str, int]]:
    dims = []
    types = []
    primary_dims = []
    suspect_numeric = 0
    for fact in facts:
        if not isinstance(fact, dict):
            continue
        types.append(fact.get("type", "other"))
        primary_dims.append(fact.get("primary_dimension", "unknown"))
        if fact.get("meta", {}).get("suspect_numeric"):
            suspect_numeric += 1
        for dim in fact.get("dimensions", []):
            dims.append(dim)
    return {
        "dimensions": _count_values(dims),
        "types": _count_values(types),
        "primary_dimensions": _count_values(primary_dims),
        "suspect_numeric": {"count": suspect_numeric},
    }


